export const productProgress=()=>document.documentElement.hasAttribute('data-pw-progress-product');
export function progressLocale(){return globalThis.PW_I18N?.locale||document.documentElement.lang||'en';}
export function progressText(source,locale=progressLocale()){
  return locale==='ru'?(ru[source]??source):source;
}
export function t(source){return productProgress()?progressText(source):source;}
export function localizeProgress(root){
  if(!productProgress())return;
  for(const e of root.querySelectorAll('[data-progress-copy]'))e.textContent=t(e.dataset.progressCopy);
  for(const e of root.querySelectorAll('[data-progress-aria]'))e.setAttribute('aria-label',t(e.dataset.progressAria));
}
export function guestClaimText(practices,seconds){
  return productProgress()&&progressLocale()==='ru'
    ?'Перенести гостевые тренировки: '+practices+' ('+seconds+' с)'
    :'Move '+practices+' guest practices ('+seconds+' sec) to this account';
}
